export function page(path) {
  const p = PAGES[path];
  if (!p) return null;
  const title = `${p.title} — ${SITE.name}`;
  return `<!doctype html><html lang="ru"><head>${headMarkup({title, desc: `${p.title}. ${description}`, path})}</head><body><header><a href="/" class="logo">скажи<span>иначе.</span></a><span class="tag">Игра, которая сближает</span><a id="connection" href="/">Играть</a></header><main class="page"><article class="panel prose"><h1>${esc(p.title)}</h1>${p.body}</article></main>${footerMarkup()}</body></html>`;
}

